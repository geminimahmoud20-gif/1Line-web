export function getSponsoredAds() {
  const saved = localStorage.getItem('oneline_sponsored_ads');
  if (saved) {
    try {
      const parsed = JSON.parse(saved);
      if (Array.isArray(parsed) && parsed.length > 0) return parsed;
    } catch (e) {
      console.error('Error parsing saved sponsored ads:', e);
    }
  }
  return DEFAULT_SPONSORED_ADS;
}

export function saveSponsoredAds(adsList) {
  localStorage.setItem('oneline_sponsored_ads', JSON.stringify(adsList));
  window.dispatchEvent(new CustomEvent('oneline_sponsored_ads_updated', { detail: adsList }));
}
