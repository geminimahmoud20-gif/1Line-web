#!/usr/bin/env node
// Rejects commit subjects that say nothing ("update", "fix", "wip"…), so the history stays readable.
//   node scripts/check-commit-message.mjs <file>        check one message (commit-msg hook)
//   node scripts/check-commit-message.mjs --range A..B  check every commit in a range (CI)
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';

const VAGUE = /^(update[sd]?|fix(es|ed)?|wip|changes?|edit(s|ed)?|misc|tmp|test|stuff|minor|cleanup|refactor|تعديل(ات)?|تحديث(ات)?|اصلاح|إصلاح)\.?$/i;
const MIN_LENGTH = 12;

function problem(subject) {
  const s = subject.trim();
  if (!s) return 'empty subject';
  if (/^(Merge|Revert) /.test(s)) return null; // generated by git
  if (VAGUE.test(s)) return `"${s}" doesn't say what changed`;
  if (s.length < MIN_LENGTH) return `"${s}" is too short (min ${MIN_LENGTH} characters)`;
  return null;
}

const HELP = `
Write the subject as what the commit does, e.g.
  Fix lost leads when the visitor submits offline
  إصلاح ضياع الطلبات عند الإرسال بدون إنترنت
Add a blank line and a body if the reason isn't obvious. See CONTRIBUTING.md.`;

const args = process.argv.slice(2);
let failures = [];
if (args[0] === '--range') {
  const out = execFileSync('git', ['log', '--format=%H%x09%s', args[1]], { encoding: 'utf8' }).trim();
  for (const line of out ? out.split('\n') : []) {
    const [sha, subject] = line.split('\t');
    const p = problem(subject);
    if (p) failures.push(`${sha.slice(0, 8)}: ${p}`);
  }
} else if (args[0]) {
  const subject = fs.readFileSync(args[0], 'utf8').split('\n').find((l) => l.trim() && !l.startsWith('#')) || '';
  const p = problem(subject);
  if (p) failures.push(p);
} else {
  console.error('usage: check-commit-message.mjs <message-file> | --range A..B');
  process.exit(2);
}
if (failures.length) {
  console.error('Commit message check failed:\n  ' + failures.join('\n  ') + HELP);
  process.exit(1);
}
